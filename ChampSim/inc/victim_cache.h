class ReplacementPolicy 
{  
  public:

    struct REP_POL_ARGS 
    {
      uint64_t access_freq;
      uint8_t pte_level;
      uint64_t pc;           // program counter associated with this access
      uint64_t pte_address;  // address of the PTE being accessed
      bool is_prefetch;      // whether the access was generated by prefetch

      REP_POL_ARGS()
        : access_freq(0), pte_level(0), pc(0), pte_address(0), is_prefetch(false)
      {}
    };

    virtual ~ReplacementPolicy() = default;	
    virtual void update_replacement_state(uint32_t set_idx, uint32_t way_idx, uint64_t curr_cycle, bool hit, REP_POL_ARGS xargs) = 0;
    virtual uint32_t find_victim(uint32_t set_idx) = 0; 
};


class LFU : public ReplacementPolicy 
{
  private:
    uint64_t num_set, num_way;
    std::vector<uint64_t> freq_ctr;
    uint32_t lfu_counter_bits;
    uint64_t lfu_counter_max;

  public:
    LFU(uint64_t _num_set, uint64_t _num_way) : num_set(_num_set), num_way(_num_way) {
      std::cout << "Using LFU replacement policy for Victim Cache" << std::endl;
      std::cout << "\tNumber of sets: " << num_set << std::endl;
      std::cout << "\tNumber of ways: " << num_way << std::endl;
      // Read counter bits from environment variable
      const char* bits_env = getenv("TXVC_REP_LFU_BITS");
      if (bits_env != nullptr) {
        lfu_counter_bits = std::stoi(bits_env);
        if (lfu_counter_bits == 0 || lfu_counter_bits > 64) {
          std::cerr << "TXVC_REP_LFU_BITS invalid or out of range (1-64), using default 8 bits." << std::endl;
          lfu_counter_bits = 8;
        }
      } else {
        lfu_counter_bits = 8;
      }
      lfu_counter_max = (lfu_counter_bits == 64) ? UINT64_MAX : ((1ULL << lfu_counter_bits) - 1);
      std::cout << "\tLFU counter bits: " << lfu_counter_bits << " (max value: " << lfu_counter_max << ")" << std::endl;
      freq_ctr.resize(num_set * num_way, 0);
    }

    virtual void update_replacement_state(uint32_t set_idx, uint32_t way_idx, uint64_t, bool hit, REP_POL_ARGS) {
      size_t idx = set_idx * num_way + way_idx;
      if (hit) {
        if (freq_ctr[idx] < lfu_counter_max) {
          freq_ctr[idx]++;
        }
      } else {
        freq_ctr[idx] = 0;
      }
    }

    virtual uint32_t find_victim(uint32_t set_idx) {
      auto begin = std::next(std::begin(freq_ctr), set_idx * num_way);
      auto end = std::next(begin, num_way);
      auto victim = std::min_element(begin, end);
      assert(begin <= victim);
      assert(victim < end);
      return static_cast<uint32_t>(std::distance(begin, victim));
    }
};


