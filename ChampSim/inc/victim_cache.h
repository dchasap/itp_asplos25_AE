class IndexHash
{
  public:
    
    virtual ~IndexHash() = default;
    
    virtual uint32_t get_set(uint64_t address) = 0; 

};

class DefaultHash : public IndexHash
{
  public:
    DefaultHash(uint32_t _num_set, uint32_t _num_way, uint32_t _offset_bits) : num_set(_num_set), num_way(_num_way), offset_bits(_offset_bits) {}
    
    virtual ~DefaultHash() = default;
    
    uint32_t get_set(uint64_t address) 
    {
      return (address >> offset_bits) & champsim::bitmask(champsim::lg2(num_set));
    }

  private:
    uint32_t num_set, num_way, offset_bits;
};


class ModuloHash : public IndexHash 
{
  public:
    ModuloHash(uint32_t _num_set, uint32_t _num_way, uint32_t _offset_bits) : num_set(_num_set), num_way(_num_way), offset_bits(_offset_bits) {}
    
    virtual ~ModuloHash() = default;
    
    uint32_t get_set(uint64_t address) 
    {
      return (address >> offset_bits) & champsim::bitmask(champsim::lg2(num_set));
    }

  private:
    uint32_t num_set, num_way, offset_bits;
};

class XORHash : public IndexHash
{
  public:
    XORHash(uint32_t _num_set, uint32_t _num_way) : num_set(_num_set), num_way(_num_way) {}
    
    virtual ~XORHash() = default;
    
    uint32_t get_set(uint64_t address) 
    {
      uint64_t block = address >> 6;
      uint32_t set_idx = (block ^ (block >> 7) ^ (block >> 13)) & (num_set - 1); 
      // we can change the last part to module for irregular number of sets
      return set_idx;
    }

  private:
    uint32_t num_set, num_way;
};

class MultiplicativeHash : public IndexHash 
{
  public:
    MultiplicativeHash(uint32_t _num_set, uint32_t _num_way) : num_set(_num_set), num_way(_num_way) {}
    
    virtual ~MultiplicativeHash() = default;
    
    uint32_t get_set(uint64_t address) 
    {
      uint64_t block = address >> 6;
      uint64_t hash = (block * 0x9E3779B97F4A7C15) >> (64 - champsim::lg2(num_set));
      return static_cast<uint32_t>(hash);
    }

  private:
    uint32_t num_set, num_way;
};

