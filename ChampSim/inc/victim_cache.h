class LRFU : public ReplacementPolicy
{
  private:
    uint64_t num_set, num_way;
    std::vector<double> score;           // decaying combined recency/frequency score per line
    std::vector<uint64_t> last_access;   // last cycle when the entry was updated
    double DECAY_FACTOR; // between 0 and 1, higher means slower decay (more frequency-biased)
  
  public:
    
    LRFU(uint64_t _num_set, uint64_t _num_way) : num_set(_num_set), num_way(_num_way)
    {
      std::cout << "Using LRFU replacement policy for Victim Cache" << std::endl;
      std::cout << "\tNumber of sets: " << num_set << std::endl;
      std::cout << "\tNumber of ways: " << num_way << std::endl;

      // read decay factor from environment (TXVC_REP_DECAY used for all
      // victim-cache replacement policies). Default to 0.9
      if (getenv("TXVC_REP_DECAY") != nullptr) {
        DECAY_FACTOR = std::atof(getenv("TXVC_REP_DECAY"));
        if (DECAY_FACTOR <= 0.0 || DECAY_FACTOR >= 1.0) {
          std::cerr << "Invalid TXVC_REP_DECAY; must be in (0,1). Using default 0.9" << std::endl;
          DECAY_FACTOR = 0.9;
        }
      } else {
        DECAY_FACTOR = 0.9;
      }

      std::cout << "\tDecay factor: " << DECAY_FACTOR << std::endl;
      score.resize(num_set * num_way);
      last_access.resize(num_set * num_way);
    }

    // Update: called on hits and on victimization.  We age the slot by the
    // number of cycles elapsed since its last update, then bump it if it's a hit.
    virtual void update_replacement_state(uint32_t set_idx, uint32_t way_idx,
                                          uint64_t curr_cycle, bool hit,
                                          REP_POL_ARGS)
    {
      uint64_t idx = set_idx * num_way + way_idx;
      if (hit) {
        uint64_t delta = curr_cycle - last_access[idx];
        if (delta > 0) {
          // exponential decay over elapsed cycles
          score[idx] *= std::pow(DECAY_FACTOR, (double)delta);
        }
        score[idx] += 1.0;
        last_access[idx] = curr_cycle;
      } else {
        // victim being evicted; reset score for incoming block
        score[idx] = 0.0;
        last_access[idx] = curr_cycle;
      }
    }

    virtual uint32_t find_victim(uint32_t set_idx)
    {
      auto begin = std::next(std::begin(score), set_idx * num_way);
      auto end = std::next(begin, num_way);

      // Find the way with the lowest score (least recently/frequently used)
      auto victim = std::min_element(begin, end);
      assert(begin <= victim);
      assert(victim < end);

      uint32_t victim_idx = static_cast<uint32_t>(std::distance(begin, victim));
      return victim_idx;
    }

};


// LFU variant that periodically right-shifts all frequency counters by 1.
// The halving interval is controlled by TXVC_REP_HALVE_PERIOD (in cycles); default is 100000.
class LFU_Halving : public ReplacementPolicy 
{
  private:
    uint64_t num_set, num_way;
    std::vector<uint64_t> freq_ctr;
    uint64_t HALVE_PERIOD;
    uint64_t next_halve;

  public:
    LFU_Halving(uint64_t _num_set, uint64_t _num_way) : num_set(_num_set), num_way(_num_way)
    {
      std::cout << "Using LFU_Halving replacement policy for Victim Cache" << std::endl;
      std::cout << "\tNumber of sets: " << num_set << std::endl;
      std::cout << "\tNumber of ways: " << num_way << std::endl;

      freq_ctr.resize(num_set * num_way);

      if (getenv("TXVC_REP_HALVE_PERIOD") != nullptr) {
        HALVE_PERIOD = std::stoull(getenv("TXVC_REP_HALVE_PERIOD"));
      } else {
        HALVE_PERIOD = 100000; // default
      }
      next_halve = HALVE_PERIOD;
      std::cout << "\tHalve period: " << HALVE_PERIOD << std::endl;
    }

    virtual void update_replacement_state(uint32_t set_idx, uint32_t way_idx,
                                          uint64_t curr_cycle, bool hit,
                                          REP_POL_ARGS)
    {
      if (curr_cycle >= next_halve) {
        for (uint64_t &val : freq_ctr)
          val >>= 1;
        next_halve = curr_cycle + HALVE_PERIOD;
      }
      if (hit) {
        freq_ctr.at(set_idx * num_way + way_idx)++;
      } else {
        freq_ctr.at(set_idx * num_way + way_idx) = 0;
      }
    }

    virtual uint32_t find_victim(uint32_t set_idx)
    {
      auto begin = std::next(std::begin(freq_ctr), set_idx * num_way);
      auto end = std::next(begin, num_way);
      auto victim = std::min_element(begin, end);
      assert(begin <= victim && victim < end);
      return static_cast<uint32_t>(std::distance(begin, victim));
    }
};


