// LFU with PC-hotness tie-breaking.  A global hotness counter is
// maintained per PC; victims are picked to minimize (freq * hotness).
class LFU_PCHot : public ReplacementPolicy {
  private:
    uint64_t num_set, num_way;
    std::vector<uint64_t> freq_ctr;
    std::vector<uint64_t> slot_pc;
    std::unordered_map<uint64_t,uint64_t> pc_hotness;
    uint64_t reset_interval;   // number of updates between hotness resets
    uint64_t update_count;     // count of calls to update_replacement_state

  public:
    LFU_PCHot(uint64_t _num_set, uint64_t _num_way)
      : num_set(_num_set), num_way(_num_way), update_count(0) {
      std::cout << "Using LFU+PC-hotness replacement policy for Victim Cache" << std::endl;
      std::cout << "\tNumber of sets: " << num_set << std::endl;
      std::cout << "\tNumber of ways: " << num_way << std::endl;
      freq_ctr.resize(num_set * num_way);
      slot_pc.resize(num_set * num_way);
      // read reset interval from environment
      if (getenv("TXVC_REP_PC_RESET_INTERVAL") != nullptr) {
        reset_interval = std::stoull(getenv("TXVC_REP_PC_RESET_INTERVAL"));
      } else {
        reset_interval = 100000; // default value
      }
      std::cout << "\tPC hotness reset interval: " << reset_interval << " updates" << std::endl;
    }

    virtual void update_replacement_state(uint32_t set_idx,
                                          uint32_t way_idx,
                                          uint64_t /*curr_cycle*/,
                                          bool hit,
                                          REP_POL_ARGS xargs) override
    {
      // global reset based on number of updates
      if (++update_count >= reset_interval) {
        for (auto &kv : pc_hotness)
          kv.second = 0;
        update_count = 0;
      }

      uint64_t idx = set_idx * num_way + way_idx;
      if (hit) {
        // hit always comes with a valid PC
        freq_ctr[idx]++;
        slot_pc[idx] = xargs.pc;
        pc_hotness[xargs.pc]++;
      } else {
        // fill: decrement hotness of outgoing PC, if any
        uint64_t old_pc = slot_pc[idx];
        if (old_pc) {
          auto &hot = pc_hotness[old_pc];
          if (hot > 0) hot--;
        }
        // install new entry
        freq_ctr[idx] = 1;
        slot_pc[idx] = xargs.pc;
        pc_hotness[xargs.pc]++;
      }
    }

    virtual uint32_t find_victim(uint32_t set_idx) override
    {
      uint32_t victim = 0;
      uint64_t min_score = UINT64_MAX;
      for (uint32_t w = 0; w < num_way; ++w) {
        uint64_t idx = set_idx * num_way + w;
        uint64_t f = freq_ctr[idx];
        uint64_t pc = slot_pc[idx];
        uint64_t hot = 1;
        auto it = pc_hotness.find(pc);
        if (it != pc_hotness.end())
          hot = it->second;
        uint64_t score = f * hot;
        if (score < min_score) {
          min_score = score;
          victim = w;
        }
      }
      return victim;
    }
};

class LRFU_WSS : public ReplacementPolicy

{

  private:

    uint64_t num_set, num_way;

    std::vector<uint64_t> freq_ctr;  // for LFU mode

    std::vector<uint64_t> last_used_cycles;  // for LRU mode

    uint64_t window_size;

    std::deque<bool> hit_history;

    uint64_t hit_count;

    double threshold;  // hit rate threshold to switch between LFU and LRU

  

  public:

    

    LRFU_WSS(uint64_t _num_set, uint64_t _num_way) : num_set(_num_set), num_way(_num_way)

    {

      std::cout << "Using LRFU_WSS replacement policy for Victim Cache" << std::endl;

      std::cout << "\tNumber of sets: " << num_set << std::endl;

      std::cout << "\tNumber of ways: " << num_way << std::endl;

      if (getenv("TXVC_REP_THRESHOLD") != nullptr) {

        threshold = std::atof(getenv("TXVC_REP_THRESHOLD"));

        if (threshold < 0.0 || threshold > 1.0) {

          std::cerr << "Invalid TXVC_REP_THRESHOLD; must be in [0,1]. Using default 0.5" << std::endl;

          threshold = 0.5;

        }

      } else {

        threshold = 0.5;

      }

      if (getenv("TXVC_REP_WINDOW_SIZE") != nullptr) {

        window_size = std::stoull(getenv("TXVC_REP_WINDOW_SIZE"));

      } else {

        window_size = 1000;

      }

      std::cout << "\tHit rate threshold: " << threshold << std::endl;

      std::cout << "\tWindow size: " << window_size << std::endl;

      freq_ctr.resize(num_set * num_way);

      last_used_cycles.resize(num_set * num_way);

      hit_count = 0;

    }

    virtual void update_replacement_state(uint32_t set_idx, uint32_t way_idx,

                                          uint64_t curr_cycle, bool hit,

                                          REP_POL_ARGS)

    {

      // Update hit history

      hit_history.push_back(hit);

      if (hit) hit_count++;

      if (hit_history.size() > window_size) {

        bool old_hit = hit_history.front();

        hit_history.pop_front();

        if (old_hit) hit_count--;

      }

      double hit_rate = hit_count / (double)hit_history.size();

      uint64_t idx = set_idx * num_way + way_idx;

      if (hit_rate > threshold) {

        // LFU mode: update frequency

        if (hit) {

          freq_ctr[idx]++;

        } else {

          freq_ctr[idx] = 0;

        }

      } else {

        // LRU mode: update recency

        if (!hit) {

          last_used_cycles[idx] = curr_cycle;

        }

      }

    }

    virtual uint32_t find_victim(uint32_t set_idx)

    {

      double hit_rate = hit_count / (double)hit_history.size();

      if (hit_rate > threshold) {

        // LFU victim: lowest frequency

        auto begin = std::next(std::begin(freq_ctr), set_idx * num_way);

        auto end = std::next(begin, num_way);

        auto victim = std::min_element(begin, end);

        assert(begin <= victim && victim < end);

        return static_cast<uint32_t>(std::distance(begin, victim));

      } else {

        // LRU victim: least recently used

        auto begin = std::next(std::begin(last_used_cycles), set_idx * num_way);

        auto end = std::next(begin, num_way);

        auto victim = std::min_element(begin, end);

        assert(begin <= victim && victim < end);

        return static_cast<uint32_t>(std::distance(begin, victim));

      }

    }

};


class LRU : public ReplacementPolicy 
{
  private:

    uint32_t num_set, num_way;
    std::vector<uint64_t> last_used_cycles;

  public:
    LRU(uint64_t _num_set, uint64_t _num_way) : num_set(_num_set), num_way(_num_way) 
    {
      std::cout << "Using LRU replacement policy for Victim Cache" << std::endl;
      std::cout << "\tNumber of sets: " << num_set << std::endl;
      std::cout << "\tNumber of ways: " << num_way << std::endl;
      last_used_cycles.resize(num_set * num_way);
    }

    virtual void update_replacement_state(uint32_t set_idx, uint32_t way_idx, uint64_t curr_cycle, bool hit, REP_POL_ARGS) 
    {
      // Mark the way as being used on the current cycle
      if (!hit) {// Skip this for writeback hits
        //std::cout << "LRU: Updating idx @ " << set_idx << " set." << std::endl;
        last_used_cycles.at(set_idx * num_way + way_idx) = curr_cycle;
      } 
    }

    virtual uint32_t find_victim(uint32_t set_idx) 
    {
      auto begin = std::next(std::begin(last_used_cycles), set_idx * num_way);
      auto end = std::next(begin, num_way);

      // Find the way whose last use cycle is most distant
      auto victim = std::min_element(begin, end);
      assert(begin <= victim);
      assert(victim < end);
      
      /*
      int _way_idx = 0;
      for (auto it = begin; it != end; ++it) {
        std::cout << "LRU: last used cycle for set " << set_idx << " at way " << _way_idx << ": " << *it << std::endl;
        _way_idx++;
      }
      */

      auto victim_idx = static_cast<uint32_t>(std::distance(begin, victim)); // cast protected by prior asserts
      //std::cout << "LRU:victim:" << victim_idx << std::endl;
      return victim_idx;
    }
};


class LFU_Leaf : public ReplacementPolicy // always prefer to evict the leaf ptes
{
  private:

    uint64_t num_set, num_way;
    std::vector<uint32_t> freq_ctr;
    std::vector<uint8_t> pte_level;
    uint8_t PTE_THRESHOLD; // consider lines with pte level >= this as leaf nodes and give them higher priority for eviction
    uint32_t ALLOWED_FREQ_DELTA;
    bool evict_leaf_nodes; // if true, will evict leaf nodes  instead of non-leaf nodes

  public: 

    LFU_Leaf(uint64_t _num_set, uint64_t _num_way) : num_set(_num_set), num_way(_num_way) 
    {
			if (getenv("TXVC_REP_PTE_THRESHOLD") != nullptr) {
					PTE_THRESHOLD = std::stoi(getenv("TXVC_REP_PTE_THRESHOLD"));
			} else {
          std::cerr << "TXVC_REP_PTE_THRESHOLD not set! Using default value of 2." << std::endl;
          PTE_THRESHOLD = 2;
      }

      evict_leaf_nodes = false;
      if (getenv("TXVC_REP_EVICT_LEAF_NODES") != nullptr) {
				char* cache_filtering_flag = getenv("TXVC_REP_EVICT_LEAF_NODES");
				if (strcmp(cache_filtering_flag, "true") == 0) {
					evict_leaf_nodes = true;
				}
      } else {
        std::cerr << "TXVC_REP_EVICT_LEAF_NODES not defined!" << std::endl;
      }

			if (getenv("TXVC_REP_ALLOWED_FREQ_DELTA") != nullptr) {
					ALLOWED_FREQ_DELTA = std::stoi(getenv("TXVC_REP_ALLOWED_FREQ_DELTA"));
			} else {
          std::cerr << "TXVC_REP_ALLOWED_FREQ_DELTA not set! Using default value of 2." << std::endl;
          ALLOWED_FREQ_DELTA = 10;
      }

      std::cout << "Using LFU_Leaf replacement policy for Victim Cache" << std::endl;
      std::cout << "\tPTE threshold for leaf classification: " << PTE_THRESHOLD << std::endl;
      std::cout << "\tEvicting leaf nodes: " << (evict_leaf_nodes ? "true" : "false") << std::endl;
      std::cout << "\tAllowed frequency delta threshold: " << ALLOWED_FREQ_DELTA << std::endl;
      freq_ctr.resize(num_set * num_way);
      pte_level.resize(num_set * num_way);
    }

    virtual void update_replacement_state(uint32_t set_idx, uint32_t way_idx, uint64_t, bool hit, REP_POL_ARGS xargs)
    {
      // Mark the way as being used on the current cycle
      //if (hit && type == WRITE) { // Skip this for writeback hits
		  //  return;
      //} No writes for PTEs
       
      if (hit) freq_ctr.at(set_idx * num_way + way_idx) ++;
      else freq_ctr.at(set_idx * num_way + way_idx) = 0;

      pte_level.at(set_idx * num_way + way_idx) = xargs.pte_level;
    }


    virtual uint32_t find_victim(uint32_t set_idx)
    {
      auto begin = std::next(std::begin(freq_ctr), set_idx * num_way);
      auto end = std::next(begin, num_way);

      // Find the way whose last use frequency cntr has the lowest value
      auto victim = std::min_element(begin, end);
      assert(begin <= victim);
      assert(victim < end);
      uint32_t lfu_victim_idx = static_cast<uint32_t>(std::distance(begin, victim)); // cast protected by prior asserts

      // this is used to flip eviction from leaf to non-leaf nodes
      bool accepted_node_type = evict_leaf_nodes ? is_leaf(pte_level.at(lfu_victim_idx), PTE_THRESHOLD) : !is_leaf(pte_level.at(lfu_victim_idx), PTE_THRESHOLD);
      if (accepted_node_type) { // if the LFU victim is a leaf pte, evict it
        return lfu_victim_idx;
      }

      // if not, we need to check which is the least frequently used leaf pte and evict it instead
      uint32_t leaf_victim_idx = 0;
      bool alt_victim_found = false;
      uint64_t min_freq = UINT64_MAX;
      for (uint32_t i = 0; i < num_way; i++) {
        accepted_node_type = evict_leaf_nodes ? is_leaf(pte_level.at(set_idx * num_way + i), PTE_THRESHOLD) : !is_leaf(pte_level.at(set_idx * num_way + i), PTE_THRESHOLD);
        if (accepted_node_type && (freq_ctr.at(set_idx * num_way + i) < min_freq)) {
          min_freq = freq_ctr.at(set_idx * num_way + i);
          leaf_victim_idx = i;
          alt_victim_found = true;
        }
      }

      // also check that the alternative candidate is not much more frequetly used than the lfu one
      // WARN: we assume that since the node type was not accepted above, the substraction has to be possitive
      //       since the real lfu candidate is the one with the lowest value.
      uint32_t frequency_delta = min_freq - freq_ctr.at(lfu_victim_idx);
      if (alt_victim_found && (frequency_delta <= ALLOWED_FREQ_DELTA)) {
        return leaf_victim_idx;
      } else {
        return lfu_victim_idx;
      }
    }

    bool is_leaf(uint8_t level, uint8_t pte_level_threshold) {
      return level > pte_level_threshold;
    }
};



class SRRIP: public ReplacementPolicy 
{
  private:
    uint64_t num_set, num_way;
    int maxRRPV; //= 3 for 2-bit RRPV;
    std::vector<int> rrpv_values;
  
  public:
    // initialize replacement state
    SRRIP(uint64_t _num_set, uint64_t _num_way, int _maxRRPV) : num_set(_num_set), num_way(_num_way), maxRRPV(_maxRRPV)
    {
      std::cout << "Using SRRIP replacement policy for Victim Cache" << std::endl;
      rrpv_values = std::vector<int>(num_set * num_way, maxRRPV); 
    }

    // called on every cache hit and cache fill
    void update_replacement_state(uint32_t set_idx, uint32_t way_idx, uint64_t, bool hit, REP_POL_ARGS)
    {
      if (hit)
        rrpv_values[set_idx * num_way + way_idx] = 0;
      else
        rrpv_values[set_idx * num_way + way_idx] = maxRRPV - 1;
    }

    // find replacement victim
    uint32_t find_victim(uint32_t set_idx)
    {
      // look for the maxRRPV line
      auto begin = std::next(std::begin(rrpv_values), set_idx * num_way);
      auto end = std::next(begin, num_way);
      auto victim = std::find(begin, end, maxRRPV); // hijack the lru field
      while (victim == end) {
        for (auto it = begin; it != end; ++it)
          ++(*it);

        victim = std::find(begin, end, maxRRPV);
      }

      assert(begin <= victim);
      assert(victim < end);
      return static_cast<uint32_t>(std::distance(begin, victim)); // cast protected by assertions
    }
};


