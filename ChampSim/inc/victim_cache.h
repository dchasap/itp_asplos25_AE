// PACIPV: Policy/Access-aware Cache Insertion & Promotion Vector.
// The vector has 5 entries:
//   idx 0..maxRRPV -> new RRPV on hit when old RRPV is idx
//   idx 4         -> insertion RRPV on fill
// This implementation keeps 2-bit RRPV semantics by default (maxRRPV = 3)
// and clamps all vector-provided values to [0, maxRRPV].
class PACIPV: public ReplacementPolicy
{
  private:
    uint64_t num_set, num_way;
    int maxRRPV;
    std::vector<uint8_t> rrpv_values;

    static constexpr std::array<uint8_t, 5> DEFAULT_IPV = {0, 1, 1, 0, 3};
    std::array<uint8_t, 5> IPV;

    uint8_t clamp_rrpv(uint8_t v) const
    {
      return static_cast<uint8_t>(std::min<int>(v, maxRRPV));
    }

    std::array<uint8_t, 5> parse_ipv_bracket(const std::string& text,
                                             const std::array<uint8_t, 5>& fallback,
                                             int line_idx) const
    {
      auto start = text.find('[');
      auto end = text.find(']', start == std::string::npos ? 0 : start + 1);
      if (start == std::string::npos || end == std::string::npos || end <= start) {
        std::cerr << "PACIPV: Malformed IPV at index " << line_idx << ". Using default." << std::endl;
        return fallback;
      }
      ++start;
      std::string values = text.substr(start, end - start);
      std::array<uint8_t, 5> parsed = fallback;
      std::istringstream vss(values);
      std::string token;
      int v = 0;
      while (std::getline(vss, token, ',')) {
        if (v >= 5) {
          std::cerr << "PACIPV: Too many entries at index " << line_idx << ". Using default." << std::endl;
          return fallback;
        }
        try {
          int value = std::stoi(token);
          if (value < 0) {
            std::cerr << "PACIPV: Negative value at index " << line_idx << ". Using default." << std::endl;
            return fallback;
          }
          parsed[v++] = clamp_rrpv(static_cast<uint8_t>(value));
        } catch (...) {
          std::cerr << "PACIPV: Invalid entry at index " << line_idx << ". Using default." << std::endl;
          return fallback;
        }
      }
      if (v != 5) {
        std::cerr << "PACIPV: Too few entries at index " << line_idx << ". Using default." << std::endl;
        return fallback;
      }
      return parsed;
    }

    bool parse_ipv_from_file(const char* file_env, const char* idx_env,
                             std::array<uint8_t, 5>& out_ipv) const
    {
      const char* file_path = std::getenv(file_env);
      const char* idx_str   = std::getenv(idx_env);
      if (!file_path || !idx_str) {
        std::cerr << "PACIPV: " << file_env << " or " << idx_env << " not set. Using defaults." << std::endl;
        return false;
      }
      int target_idx = -1;
      try { target_idx = std::stoi(idx_str); }
      catch (...) {
        std::cerr << "PACIPV: Invalid index value in " << idx_env << ". Using defaults." << std::endl;
        return false;
      }
      std::ifstream infile(file_path);
      if (!infile) {
        std::cerr << "PACIPV: Could not open IPV pairs file: " << file_path << ". Using defaults." << std::endl;
        return false;
      }
      std::string line;
      while (std::getline(infile, line)) {
        if (line.empty() || line[0] == '#') continue;
        std::istringstream linestream(line);
        int idx = -1;
        char colon;
        linestream >> idx >> colon;
        if (colon != ':' || idx != target_idx) continue;
        std::string rest;
        std::getline(linestream, rest);
        out_ipv = parse_ipv_bracket(rest, DEFAULT_IPV, target_idx);
        return true;
      }
      std::cerr << "PACIPV: Index " << target_idx << " not found in file. Using defaults." << std::endl;
      return false;
    }

    const std::array<uint8_t, 5>& select_ipv(const REP_POL_ARGS& xargs) const
    {
      static_cast<void>(xargs);
      return IPV;
    }

  public:
    PACIPV(uint64_t _num_set, uint64_t _num_way, int _maxRRPV = 3)
      : num_set(_num_set), num_way(_num_way), maxRRPV(_maxRRPV),
        rrpv_values(_num_set * _num_way, static_cast<uint8_t>(_maxRRPV)),
        IPV(DEFAULT_IPV)
    {
      // Load a single IPV from a file with lines in the format:
      //   INDEX: [v0,v1,v2,v3,v4]
      // Set TXVC_PACIPV_DEMAND_VECTOR_FILE and TXVC_PACIPV_DEMAND_VECTOR_IDX.
      // If those are not set, fall back to TXVC_PACIPV_DEMAND_VEC.
      if (!parse_ipv_from_file("TXVC_PACIPV_DEMAND_VECTOR_FILE",
                               "TXVC_PACIPV_DEMAND_VECTOR_IDX",
                               IPV)) {
        const char* env_value = std::getenv("TXVC_PACIPV_DEMAND_VEC");
        if (env_value != nullptr) {
          IPV = parse_ipv_bracket(env_value, DEFAULT_IPV, -1);
        }
      }

      std::cout << "Using PACIPV replacement policy for Victim Cache" << std::endl;
      std::cout << "\tNumber of sets: " << num_set << std::endl;
      std::cout << "\tNumber of ways: " << num_way << std::endl;
      std::cout << "\tMax RRPV: " << maxRRPV << std::endl;
      std::cout << "\tIPV: [" << static_cast<int>(IPV[0]) << ", " << static_cast<int>(IPV[1]) << ", "
                << static_cast<int>(IPV[2]) << ", " << static_cast<int>(IPV[3]) << ", "
                << static_cast<int>(IPV[4]) << "]" << std::endl;
    }

    void update_replacement_state(uint32_t set_idx, uint32_t way_idx, uint64_t, bool hit, REP_POL_ARGS xargs) override
    {
      uint64_t idx = static_cast<uint64_t>(set_idx) * num_way + way_idx;
      const auto& ipv = select_ipv(xargs);

      if (hit) {
        uint8_t old_rrpv = clamp_rrpv(rrpv_values[idx]);
        rrpv_values[idx] = clamp_rrpv(ipv[old_rrpv]);
      } else {
        // insertion uses vector-defined insertion RRPV (entry 4)
        rrpv_values[idx] = clamp_rrpv(ipv[4]);
      }
    }

    uint32_t find_victim(uint32_t set_idx) override
    {
      auto begin = std::next(std::begin(rrpv_values), static_cast<uint64_t>(set_idx) * num_way);
      auto end = std::next(begin, num_way);

      while (true) {
        auto victim = std::find(begin, end, static_cast<uint8_t>(maxRRPV));
        if (victim != end) {
          return static_cast<uint32_t>(std::distance(begin, victim));
        }

        // Age every line toward maxRRPV; saturate to avoid wrap-around.
        for (auto it = begin; it != end; ++it) {
          if (*it < static_cast<uint8_t>(maxRRPV))
            ++(*it);
        }
      }
    }
};


// PACIPV_LFU: PACIPV-style insertion/promotion vectors with LFU victim selection.
// The vector has 5 entries:
//   idx 0..maxRRPV -> new RRPV-like state on hit when old state is idx
//   idx 4         -> insertion state on fill
// We convert those states into LFU buckets where a higher bucket means "hotter".
class PACIPV_LFU: public ReplacementPolicy
{
  private:
    uint64_t num_set, num_way;
    int maxRRPV;
    std::vector<uint8_t> freq_values;

    static constexpr std::array<uint8_t, 5> DEFAULT_IPV_DEMAND = {0, 1, 1, 0, 3};
    static constexpr std::array<uint8_t, 5> DEFAULT_IPV_PREFETCH = {0, 1, 0, 0, 3};
    std::array<uint8_t, 5> IPV_DEMAND;
    std::array<uint8_t, 5> IPV_PREFETCH;

    uint8_t clamp_rrpv(uint8_t v) const
    {
      return static_cast<uint8_t>(std::min<int>(v, maxRRPV));
    }

    std::array<uint8_t, 5> parse_ipv_env(const char* env_name, const std::array<uint8_t, 5>& fallback) const
    {
      const char* env_value = std::getenv(env_name);
      if (env_value == nullptr)
        return fallback;

      std::string raw(env_value);
      if (!raw.empty() && raw.front() == '[') raw.erase(raw.begin());
      if (!raw.empty() && raw.back() == ']') raw.pop_back();

      std::array<uint8_t, 5> parsed = fallback;
      std::stringstream ss(raw);
      std::string token;
      int idx = 0;

      while (std::getline(ss, token, ',')) {
        if (idx >= 5) {
          std::cerr << env_name << " has more than 5 entries. Using default." << std::endl;
          return fallback;
        }

        try {
          int value = std::stoi(token);
          if (value < 0) {
            std::cerr << env_name << " contains negative value. Using default." << std::endl;
            return fallback;
          }
          parsed[idx++] = clamp_rrpv(static_cast<uint8_t>(value));
        } catch (...) {
          std::cerr << env_name << " contains invalid entry. Using default." << std::endl;
          return fallback;
        }
      }

      if (idx != 5) {
        std::cerr << env_name << " must provide exactly 5 comma-separated values. Using default." << std::endl;
        return fallback;
      }

      return parsed;
    }

    uint8_t clamp_freq(uint8_t v) const
    {
      return static_cast<uint8_t>(std::min<int>(v, maxRRPV));
    }

    const std::array<uint8_t, 5>& select_ipv(const REP_POL_ARGS& xargs) const
    {
      return xargs.is_prefetch ? IPV_PREFETCH : IPV_DEMAND;
    }

    uint8_t rrpv_from_freq(uint8_t freq) const
    {
      return static_cast<uint8_t>(maxRRPV - clamp_freq(freq));
    }

    uint8_t freq_from_rrpv(uint8_t rrpv) const
    {
      return static_cast<uint8_t>(maxRRPV - clamp_rrpv(rrpv));
    }

  public:
    PACIPV_LFU(uint64_t _num_set, uint64_t _num_way, int _maxRRPV = 3)
      : num_set(_num_set), num_way(_num_way), maxRRPV(_maxRRPV), freq_values(_num_set * _num_way, 0),
        IPV_DEMAND(parse_ipv_env("TXVC_PACIPV_DEMAND_VEC", DEFAULT_IPV_DEMAND)),
        IPV_PREFETCH(parse_ipv_env("TXVC_PACIPV_PREFETCH_VEC", DEFAULT_IPV_PREFETCH))
    {
      std::cout << "Using PACIPV_LFU replacement policy for Victim Cache" << std::endl;
      std::cout << "\tNumber of sets: " << num_set << std::endl;
      std::cout << "\tNumber of ways: " << num_way << std::endl;
      std::cout << "\tMax RRPV/Frequency bucket: " << maxRRPV << std::endl;
      std::cout << "\tDemand IPV: [" << static_cast<int>(IPV_DEMAND[0]) << ", " << static_cast<int>(IPV_DEMAND[1]) << ", "
                << static_cast<int>(IPV_DEMAND[2]) << ", " << static_cast<int>(IPV_DEMAND[3]) << ", "
                << static_cast<int>(IPV_DEMAND[4]) << "]" << std::endl;
      std::cout << "\tPrefetch IPV: [" << static_cast<int>(IPV_PREFETCH[0]) << ", " << static_cast<int>(IPV_PREFETCH[1]) << ", "
                << static_cast<int>(IPV_PREFETCH[2]) << ", " << static_cast<int>(IPV_PREFETCH[3]) << ", "
                << static_cast<int>(IPV_PREFETCH[4]) << "]" << std::endl;
    }

    void update_replacement_state(uint32_t set_idx, uint32_t way_idx, uint64_t, bool hit, REP_POL_ARGS xargs) override
    {
      uint64_t idx = static_cast<uint64_t>(set_idx) * num_way + way_idx;
      const auto& ipv = select_ipv(xargs);

      if (hit) {
        uint8_t old_rrpv = rrpv_from_freq(freq_values[idx]);
        uint8_t new_rrpv = clamp_rrpv(ipv[old_rrpv]);
        freq_values[idx] = freq_from_rrpv(new_rrpv);
      } else {
        // insertion uses vector-defined insertion state (entry 4)
        freq_values[idx] = freq_from_rrpv(ipv[4]);
      }
    }

    uint32_t find_victim(uint32_t set_idx) override
    {
      auto begin = std::next(std::begin(freq_values), static_cast<uint64_t>(set_idx) * num_way);
      auto end = std::next(begin, num_way);

      // LFU victim: evict the coldest line (lowest frequency bucket).
      auto victim = std::min_element(begin, end);
      assert(begin <= victim);
      assert(victim < end);
      return static_cast<uint32_t>(std::distance(begin, victim));
    }
};


class HREP : public ReplacementPolicy 
{
  private:
      
    uint64_t num_set, num_way;
    std::vector<uint64_t> freq_ctr;
  
  public: 

    HREP(uint64_t _num_set, uint64_t _num_way) : num_set(_num_set), num_way(_num_way) 
    {
      std::cout << "Using HREP replacement policy for Victim Cache" << std::endl;
      std::cout << "\tNumber of sets: " << num_set << std::endl;
      std::cout << "\tNumber of ways: " << num_way << std::endl;
      freq_ctr.resize(num_set * num_way);
    }

    virtual void update_replacement_state(uint32_t set_idx, uint32_t way_idx, uint64_t, bool hit, REP_POL_ARGS)
    {
      // Mark the way as being used on the current cycle
      //if (hit && type == WRITE) { // Skip this for writeback hits
		  //  return;
      //} No writes for PTEs
       
      if (hit) {
        //std::cout << "LFU: Increasing idx @ " << set_idx << " set."  << std::endl;
        freq_ctr.at(set_idx * num_way + way_idx) ++;
      }  else { 
        //std::cout << "LFU: Resetting idx @ " << set_idx << " set." << std::endl;
        freq_ctr.at(set_idx * num_way + way_idx) = 0;
      }
    }

    virtual uint32_t find_victim(uint32_t set_idx)
    {
      auto begin = std::next(std::begin(freq_ctr), set_idx * num_way);
      auto end = std::next(begin, num_way);

      // Find the way whose last use frequency cntr has the lowest value
      auto victim = std::min_element(begin, end);
      assert(begin <= victim);
      assert(victim < end);

      /*
      int _way_idx = 0;
      for (auto it = begin; it != end; ++it) {
        std::cout << "LFU: frequency counter for set " << set_idx << " at way " << _way_idx << ": " << *it << std::endl;
        _way_idx++;
      }
      */

      uint32_t victim_idx = static_cast<uint32_t>(std::distance(begin, victim)); // cast protected by prior asserts
	    //std::cout << "LFU:victim:" << victim_idx << std::endl;
	    return victim_idx;
    }
};

